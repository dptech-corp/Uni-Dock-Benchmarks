#!/usr/bin/env python3
"""
Aggregate benchmark outputs from one or more run directories.

This script merges `metrics.csv`/`res.csv` from multiple runs and optionally
produces quick comparison plots when matplotlib is available.
"""
from __future__ import annotations

import argparse
import logging
from pathlib import Path
from typing import Iterable

try:
    import pandas as pd
except Exception:  # pragma: no cover
    pd = None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Summarize Uni-Dock benchmark results from multiple run directories."
    )
    parser.add_argument(
        "--runs",
        nargs="+",
        required=True,
        help="Run directories generated by scripts/run_test.py (e.g. results/run_a results/run_b).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="analysis",
        help="Output directory for merged tables and plots (default: analysis).",
    )
    parser.add_argument(
        "--name",
        type=str,
        default="summary",
        help="Prefix for generated files (default: summary).",
    )
    parser.add_argument(
        "--no-plot",
        action="store_true",
        help="Disable plot generation and export tables only.",
    )
    return parser.parse_args()


def iter_run_dirs(paths: Iterable[str]) -> list[Path]:
    run_dirs: list[Path] = []
    for p in paths:
        rp = Path(p).expanduser().resolve()
        if not rp.exists():
            logging.warning("Skip missing run dir: %s", rp)
            continue
        run_dirs.append(rp)
    return run_dirs


def read_table(fp: Path) -> pd.DataFrame | None:
    if not fp.exists():
        return None
    try:
        return pd.read_csv(fp)
    except Exception as exc:  # pragma: no cover
        logging.warning("Failed reading %s: %s", fp, exc)
        return None


def add_run_info(df: pd.DataFrame, run_dir: Path) -> pd.DataFrame:
    out = df.copy()
    out.insert(0, "run_name", run_dir.name)
    out.insert(1, "run_dir", str(run_dir))
    return out


def maybe_plot(metrics_df: pd.DataFrame, output_dir: Path, name: str) -> None:
    try:
        import matplotlib.pyplot as plt
    except Exception:
        logging.info("matplotlib is unavailable; skip plot generation.")
        return

    if "hit_rate_rmsd2.0" in metrics_df.columns:
        df = metrics_df.copy()
        if "mode" not in df.columns:
            df["mode"] = "unknown"
        df["label"] = df["run_name"] + " | " + df["dataset"].astype(str) + " | " + df["mode"].astype(str)
        fig, ax = plt.subplots(figsize=(12, 6))
        ax.bar(df["label"], df["hit_rate_rmsd2.0"])
        ax.set_ylabel("Top1 Hit Rate (RMSD<2.0)")
        ax.set_title("Molecular Docking Benchmark Comparison")
        ax.tick_params(axis="x", rotation=80)
        fig.tight_layout()
        fp = output_dir / f"{name}_docking_hit_rate.png"
        fig.savefig(fp, dpi=200)
        plt.close(fig)
        logging.info("Saved plot: %s", fp)

    ef_col = "Enrichment (1%)"
    if ef_col in metrics_df.columns:
        df = metrics_df.copy()
        if "Mode" not in df.columns:
            df["Mode"] = "unknown"
        df["label"] = df["run_name"] + " | " + df["dataset"].astype(str) + " | " + df["Mode"].astype(str)
        fig, ax = plt.subplots(figsize=(12, 6))
        ax.bar(df["label"], df[ef_col])
        ax.set_ylabel("EF@1%")
        ax.set_title("Virtual Screening Benchmark Comparison")
        ax.tick_params(axis="x", rotation=80)
        fig.tight_layout()
        fp = output_dir / f"{name}_screening_ef1.png"
        fig.savefig(fp, dpi=200)
        plt.close(fig)
        logging.info("Saved plot: %s", fp)


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="[%(levelname)s] %(message)s")
    args = parse_args()
    if pd is None:
        logging.error("pandas is required. Please run: pip install pandas")
        return 1

    run_dirs = iter_run_dirs(args.runs)
    if not run_dirs:
        logging.error("No valid run directory found.")
        return 1

    output_dir = Path(args.output).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    metrics_list: list[pd.DataFrame] = []
    res_list: list[pd.DataFrame] = []

    for run_dir in run_dirs:
        fp_metrics = run_dir / "metrics.csv"
        fp_res = run_dir / "res.csv"

        df_metrics = read_table(fp_metrics)
        if df_metrics is not None and not df_metrics.empty:
            metrics_list.append(add_run_info(df_metrics, run_dir))
        else:
            logging.warning("metrics.csv missing or empty in %s", run_dir)

        df_res = read_table(fp_res)
        if df_res is not None and not df_res.empty:
            res_list.append(add_run_info(df_res, run_dir))
        else:
            logging.warning("res.csv missing or empty in %s", run_dir)

    if not metrics_list and not res_list:
        logging.error("No valid metrics.csv/res.csv found from the provided runs.")
        return 1

    if metrics_list:
        df_metrics_all = pd.concat(metrics_list, ignore_index=True)
        fp = output_dir / f"{args.name}_metrics_merged.csv"
        df_metrics_all.to_csv(fp, index=False)
        logging.info("Saved merged metrics: %s", fp)
    else:
        df_metrics_all = pd.DataFrame()

    if res_list:
        df_res_all = pd.concat(res_list, ignore_index=True)
        fp = output_dir / f"{args.name}_res_merged.csv"
        df_res_all.to_csv(fp, index=False)
        logging.info("Saved merged run records: %s", fp)

    if (not args.no_plot) and (not df_metrics_all.empty):
        maybe_plot(df_metrics_all, output_dir, args.name)

    logging.info("Analysis complete. Output directory: %s", output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
